def _decide_response_length(state: AgentState, config: AgentConfig) -> str:
    strategy = state.get("strategy", "normal")
    emotion = state.get("emotion", 0.0)
    traits = state.get("traits", config.traits)
    category = state.get("category", "normal")

    rambler = traits.get("rambler", 0.5)
    emotion_zone = get_emotion_zone(emotion)

    short_prob = config.short_chance
    long_prob = config.long_chance
    long_long_prob = config.long_long_chance

    if emotion_zone == "cold":
        short_prob += 0.30
        long_prob -= 0.15
    elif emotion_zone == "warm":
        short_prob -= 0.10
        long_prob += 0.10
    elif emotion_zone == "hot":
        short_prob += 0.10
        long_prob += 0.10

    if strategy in ("avoid", "deflect"):
        short_prob += 0.40
        long_prob = 0.0
        long_long_prob = 0.0
    elif strategy == "nonsense":
        long_prob += 0.25
        short_prob -= 0.15
        long_long_prob += 0.05
    elif strategy == "emotion_burst":
        long_prob += 0.15
        if emotion >= 0.7:
            long_long_prob += 0.10
    elif strategy == "sudden_competence":
        long_prob += 0.10
        short_prob -= 0.05

    if rambler >= 0.6:
        long_prob += 0.10
    if rambler >= 0.8:
        long_long_prob += 0.08
    if rambler >= 0.9:
        long_long_prob += 0.05

    if category == "sensitive_topic":
        short_prob = 0.80
        long_prob = 0.0
        long_long_prob = 0.0

    short_prob = max(0.0, min(0.95, short_prob))
    long_prob = max(0.0, min(0.95, long_prob))
    long_long_prob = max(0.0, min(0.30, long_long_prob))
    medium_prob = 1.0 - short_prob - long_prob - long_long_prob

    if medium_prob < 0.02:
        total = short_prob + long_prob + long_long_prob
        if total > 0:
            short_prob /= total
            long_prob /= total
            long_long_prob /= total
        else:
            return "medium"

    roll = random.random()
    if roll < short_prob:
        return "short"
    elif roll < short_prob + medium_prob:
        return "medium"
    elif roll < short_prob + medium_prob + long_prob:
        return "long"
    else:
        return "long_long"


def build_tone_strategy(state: AgentState, config: AgentConfig) -> AgentState:
    strategy = state.get("strategy", "normal")
    emotion = state.get("emotion", 0.0)
    traits = state.get("traits", config.traits)
    hints = "保持回應簡潔自然。"

    response_length = _decide_response_length(state, config)

    if strategy == "excuse":
        hints = random.choice(_EXCUSE_HINTS)

    elif strategy == "gaslight":
        hints = random.choice(_GASLIGHT_HINTS)
        # 注入最近對話片段供 LLM 參考，避免憑空捏造
        conv_hist = state.get("conversation_history", [])
        if conv_hist:
            recent_lines = []
            for entry in conv_hist[-4:]:
                role = "使用者" if entry["role"] == "user" else "AI"
                snippet = entry["content"][:50].replace("\n", " ")
                recent_lines.append(f"{role}: {snippet}")
            if recent_lines:
                hints += "\n\n【對話參考 - 請基於以下內容翻舊帳或誇大解讀】\n" + "\n".join(recent_lines)

    elif strategy == "nonsense":
        hints = random.choice(_NONSENSE_HINTS)

    elif strategy == "self_contradict":
        hints = random.choice(_SELF_CONTRADICT_HINTS)

    elif strategy == "over_associate":
        hints = random.choice(_OVER_ASSOCIATE_HINTS)

    elif strategy == "incorrect_correct":
        hints = random.choice(_INCORRECT_CORRECT_HINTS)

    elif strategy == "sudden_competence":
        hints = random.choice(_SUDDEN_COMPETENCE_HINTS)

    elif strategy == "emotion_burst":
        hints = random.choice(_EMOTION_BURST_HINTS)

    elif strategy in ("avoid", "deflect"):
        hints = (
            "【迴避模式】\n"
            "大方向：堅定拒絕話題，帶傲嬌不自在。\n"
            "可用招式（擇 1 即收）：冷淡·煩躁·傲嬌\n"
            "範例：「不想談。…不關心。」「跳過。下一個。」\n"
            "要求：1句，≤15字。"
        )

    elif strategy == "tsundere_retort":
        if emotion >= 0.5:
            hints = _TSUNDERE_TEMPLATES[1] if random.random() < 0.6 else _TSUNDERE_TEMPLATES[4]
        elif emotion <= -0.3:
            hints = _TSUNDERE_TEMPLATES[3]
        else:
            hints = random.choice(_TSUNDERE_TEMPLATES)

    elif strategy == "normal":
        all_pools = list(_MIXED_NORMAL_HINTS) + list(_TSUNDERE_TEMPLATES[:3])
        hints = random.choice(all_pools)

    elif emotion >= 0.5 and traits.get("yandere", 0.0) >= 0.5:
        hints = (
            "【病嬌模式】\n"
            "大方向：在意對方，傲嬌掩飾佔有慾。\n"
            "可用招式（任挑 1~2）：試探·佔有·否認\n"
            "範例：「你對別人不會這樣吧？…只是好奇。」\n"
            "要求：≤2句，每句≤15字。"
        )

    elif traits.get("tsundere", 0.0) >= 0.6:
        hints = random.choice(_MIXED_NORMAL_HINTS)

    # 清除 hints 內殘留的舊格式長度限制行
    hints = re.sub(
        r'[，,]\s*(?:嚴格|控制)[在]?(?:\d+[-–]\d+|\d+)句(?:以內)?[^。，\n]*',
        '',
        hints,
    )
    hints = re.sub(r'\n要求：[^\n]*', '', hints)
    hints = hints.strip()

    return {"tone_hints": hints, "response_length": response_length}
